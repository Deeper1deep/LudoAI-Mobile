import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
}

val versionProps = Properties().apply { file("../version.properties").inputStream().use { load(it) } }
val vMajor = versionProps.getProperty("VERSION_MAJOR").toInt()
val vMinor = versionProps.getProperty("VERSION_MINOR").toInt()
// The publish workflow passes -PversionCode=<latest published + 1>. Locally the file value is used.
val vCode = (project.findProperty("versionCode") as String?)?.toInt() ?: versionProps.getProperty("VERSION_CODE").toInt()
val vName = (project.findProperty("versionName") as String?) ?: "$vMajor.$vMinor.${vCode - 1}"

// ---- Permanent signing identity (never generated by the build) ----
val ksPath: String? = System.getenv("KEYSTORE_PATH")
val ksPass: String? = System.getenv("KEYSTORE_PASSWORD")
val ksAlias: String? = System.getenv("KEY_ALIAS")
val keyPass: String? = System.getenv("KEY_PASSWORD")
val signingConfigured = !ksPath.isNullOrBlank() && file(ksPath).exists() && !ksPass.isNullOrBlank() &&
    !ksAlias.isNullOrBlank() && !keyPass.isNullOrBlank()

android {
    namespace = "com.ludoai.assistant"
    compileSdk = 34

    defaultConfig {
        // PERMANENT: never change after the first public release.
        applicationId = "com.ludoai.assistant"
        minSdk = 26
        targetSdk = 34
        versionCode = vCode
        versionName = vName
        buildConfigField("String", "UPDATES_OWNER", "\"Deeper1deep\"")
        buildConfigField("String", "UPDATES_REPO", "\"LudoAI-Updates\"")
    }

    signingConfigs {
        if (signingConfigured) {
            create("release") {
                storeFile = file(ksPath!!)
                storePassword = ksPass
                keyAlias = ksAlias
                keyPassword = keyPass
                enableV1Signing = true
                enableV2Signing = true
                enableV3Signing = true
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (signingConfigured) signingConfig = signingConfigs.getByName("release")
        }
        debug { applicationIdSuffix = ".debug"; versionNameSuffix = "-debug" }
    }

    buildFeatures { compose = true; buildConfig = true }
    composeOptions { kotlinCompilerExtensionVersion = "1.5.14" }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    packaging { resources.excludes += "/META-INF/{AL2.0,LGPL2.1}" }
    lint { abortOnError = false }
}

// A release build without the permanent signing configuration must fail, never fall back to another key.
gradle.taskGraph.whenReady {
    val releaseRequested = allTasks.any { it.project == project && (it.name.contains("Release") && (it.name.startsWith("assemble") || it.name.startsWith("package") || it.name.startsWith("bundle"))) }
    if (releaseRequested && !signingConfigured) {
        throw GradleException(
            "RELEASE SIGNING CONFIGURATION MISSING. Set KEYSTORE_PATH, KEYSTORE_PASSWORD, KEY_ALIAS and KEY_PASSWORD " +
                "(see docs/SIGNING.md). The build will NOT generate a replacement key."
        )
    }
}

